import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const modules = ['src/layout.js', 'src/plugin.js'].map(f => readFileSync(resolve(root, f), 'utf8'));
const bundle = `/* Kanban Dependency Map v1.0.0 — generated by node scripts/build.mjs */\n(function () {\n"use strict";\n${modules.join('\n\n')}\n})();\n`;
writeFileSync(resolve(root, 'dashboard/dist/index.js'), bundle);
console.log(`Built dashboard/dist/index.js (${bundle.length} bytes)`);
